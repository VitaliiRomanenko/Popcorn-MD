/**
 * Represents a spoken language.
 */
export interface Language {
  /** The ISO 639‑1 code of the language (e.g., "en"). */
  iso_639_1: string;
  /** The English name of the language (e.g., "English"). */
  english_name: string;
  /** The native name of the language (e.g., "English"). */
  name: string;
}
